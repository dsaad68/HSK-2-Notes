#!/usr/bin/env python3
"""
Subset LXGW WenKai to only the Chinese characters used by the site.

Usage:
  pip install fonttools brotli
  python3 site/tools/subset_font.py /path/to/LXGWWenKai-Regular.ttf /path/to/LXGWWenKai-Medium.ttf

Download the TTFs from https://github.com/lxgw/LxgwWenKai/releases (SIL OFL 1.1).
Re-run after adding new Chinese text to the site.
"""
import base64
import pathlib
import re
import sys
import tempfile

from fontTools import subset

SITE = pathlib.Path(__file__).resolve().parent.parent
SKIP = {"hanzi-data.js", "hanzi-writer.min.js"}

text = set()
for p in list(SITE.rglob("*.js")) + list(SITE.rglob("*.html")):
    if p.name in SKIP:
        continue
    text.update(re.findall(r"[⺀-⿟　-〿㐀-鿿＀-￯\U00020000-\U0002ffff]", p.read_text("utf8")))
text.update("，。：；！？、（）《》“”‘’")
chars = "".join(sorted(text))
print(f"{len(chars)} unique CJK characters")

faces = []
tmp = pathlib.Path(tempfile.mkdtemp())
for src, name, weight in zip(sys.argv[1:3], ["wenkai-regular", "wenkai-medium"], ["400", "500 700"]):
    out = tmp / f"{name}.woff2"
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.name_IDs = ["*"]
    font = subset.load_font(src, opts)
    sub = subset.Subsetter(opts)
    sub.populate(text=chars + "abcdefghijklmnopqrstuvwxyz0123456789")
    sub.subset(font)
    subset.save_font(font, str(out), opts)
    print(f"subset {name}: {out.stat().st_size // 1024} KB")
    b64 = base64.b64encode(out.read_bytes()).decode()
    faces.append(f'@font-face{{font-family:"WenKai";font-weight:{weight};font-display:swap;'
                 f'src:url(data:font/woff2;base64,{b64}) format("woff2");}}')

# Inline the fonts so the site also works when index.html is opened straight from disk
# (browsers block @font-face file loads on file:// pages).
css = SITE / "assets" / "css" / "fonts.css"
css.write_text("/* LXGW WenKai subset (SIL OFL 1.1), generated by tools/subset_font.py */\n" + "\n".join(faces) + "\n")
print(f"wrote {css.relative_to(SITE)} ({css.stat().st_size // 1024} KB)")
